/**
 * The bridge between a ComfyUI prompt id and the canvas task that asked for it.
 *
 * ## Why a registry at all
 *
 * A finished image comes back on the generation response, but everything that
 * happens *while* it renders arrives on the separate SSE stream
 * (`src/progress.ts`). Those frames carry only ComfyUI's `prompt_id`; the marker
 * naming the canvas task is a browser-generated `clientId` that only the
 * submitting request knows. So the host keeps this map from `prompt_id` to
 * `{ clientId, boardId }` for the lifetime of one run, and the progress bridge
 * looks every event up against it (DD7, `../docs/usage-reference.md` §4.3).
 *
 * ## Why it is memory only
 *
 * A run registry is a *session* bridge, not durable state: after a restart an
 * old run's SSE frames are meaningless, and the finished images are recorded on
 * the board through the ordinary write path. Persisting this map would only
 * reintroduce the stale-state problem the canvas design deliberately avoids.
 *
 * ## Lifetime
 *
 * `register` happens at submission (the adapter's `onPromptId` hook), so the
 * `run` event can reach the panel while ComfyUI is still queueing. `release`
 * happens when the generation call returns or throws; from then on the record
 * keeps answering for {@link RUN_TTL_MS} so frames that were already in flight
 * (`done`, a late `progress`) still resolve. Lookups and registrations sweep.
 *
 * @module runs
 */

/**
 * How long a released run keeps answering lookups, in milliseconds.
 *
 * Five minutes is several orders of magnitude longer than the gap between
 * ComfyUI finishing and the HTTP response reaching the panel; it exists to
 * absorb a stalled SSE connection, not to keep dead runs around for the
 * session.
 */
export const RUN_TTL_MS = 5 * 60_000

/** What the progress bridge needs to attach one run to its canvas task node. */
export interface RunTarget {
  /** Canvas task id generated by the panel (`c` + base36); see `isStudioClientId`. */
  readonly clientId: string
  /** Board the result will be recorded on; absent when the panel did not name one. */
  readonly boardId?: string
}

/** One registered run, as `lookup` returns it. */
export interface RunRecord extends RunTarget {
  /** ComfyUI's id for this run, from the `/prompt` answer. */
  readonly promptId: string
  /** Clock reading at registration, kept for diagnostics and tests. */
  readonly registeredAt: number
  /** When the record stops answering; `undefined` while the run is still live. */
  readonly expiresAt?: number
}

/** The observable, session-lifetime map one Studio route registration owns. */
export interface RunRegistry {
  /**
   * Remember one submission.
   *
   * Never throws: this runs inside the adapter's submit hook, where an exception
   * would fail a run ComfyUI has already accepted. A blank id is ignored.
   *
   * @param promptId - ComfyUI's prompt id for the run.
   * @param target - canvas task and board the run belongs to.
   * @returns the stored record, or `undefined` when the ids were blank.
   */
  register(promptId: string, target: RunTarget): RunRecord | undefined
  /** The live (or recently finished) record for one prompt id, if any. */
  lookup(promptId: string): RunRecord | undefined
  /**
   * Mark the generation call as over; the record keeps answering for the TTL.
   *
   * @param promptId - the run that settled.
   * @returns whether a record was there to release.
   */
  release(promptId: string): boolean
  /**
   * Drop one record immediately.
   *
   * @param promptId - the run to forget.
   * @returns whether it existed.
   */
  forget(promptId: string): boolean
  /** Drop every expired record. @returns how many were dropped. */
  sweep(): number
  /**
   * Observe registrations.
   *
   * One throwing listener must not starve the rest; the bridge already isolates
   * its own subscribers and this is the same discipline one layer down.
   *
   * @param listener - receives one record per registration.
   * @returns idempotent unsubscribe.
   */
  subscribe(listener: (record: RunRecord) => void): () => void
  /** Number of records still answering lookups. */
  size(): number
}

/** The clock and TTL seams; production takes the defaults. */
export interface RunRegistryOptions {
  /** Record lifetime after `release` in milliseconds (default {@link RUN_TTL_MS}). */
  readonly ttlMs?: number
  /** Clock override, for tests; defaults to `Date.now`. */
  readonly now?: () => number
}

/** Mutable view kept in the map. */
interface StoredRun {
  promptId: string
  clientId: string
  boardId?: string
  registeredAt: number
  expiresAt?: number
}

/** Copy a stored run, so no caller can mutate what the map holds. */
function snapshot(run: StoredRun): RunRecord {
  return {
    promptId: run.promptId,
    clientId: run.clientId,
    ...(run.boardId === undefined ? {} : { boardId: run.boardId }),
    registeredAt: run.registeredAt,
    ...(run.expiresAt === undefined ? {} : { expiresAt: run.expiresAt }),
  }
}

/**
 * Create one in-memory run registry.
 *
 * @param options - TTL and clock overrides (both exist as test seams).
 * @returns the registry; empty until something registers.
 */
export function createRunRegistry(options: RunRegistryOptions = {}): RunRegistry {
  const ttlMs = Math.max(0, options.ttlMs ?? RUN_TTL_MS)
  const now = options.now ?? Date.now
  const records = new Map<string, StoredRun>()
  const listeners = new Set<(record: RunRecord) => void>()

  /** True when a released record has reached its TTL. */
  function expired(run: StoredRun, at: number): boolean {
    return run.expiresAt !== undefined && at >= run.expiresAt
  }

  /** Drop every expired record; returns how many are gone. */
  function sweep(): number {
    const at = now()
    let dropped = 0
    for (const [promptId, run] of records) {
      if (!expired(run, at)) continue
      records.delete(promptId)
      dropped += 1
    }
    return dropped
  }

  return {
    register(promptId, target) {
      if (promptId.length === 0 || target.clientId.length === 0) return undefined
      sweep()
      const stored: StoredRun = {
        promptId,
        clientId: target.clientId,
        ...(target.boardId === undefined ? {} : { boardId: target.boardId }),
        registeredAt: now(),
      }
      records.set(promptId, stored)
      const record = snapshot(stored)
      for (const listener of [...listeners]) {
        try {
          listener(record)
        } catch {
          // A broken observer must not fail the submission it observes.
        }
      }
      return record
    },
    lookup(promptId) {
      const run = records.get(promptId)
      if (run === undefined) return undefined
      if (expired(run, now())) {
        records.delete(promptId)
        return undefined
      }
      return snapshot(run)
    },
    release(promptId) {
      const run = records.get(promptId)
      if (run === undefined) return false
      run.expiresAt = now() + ttlMs
      return true
    },
    forget(promptId) {
      return records.delete(promptId)
    },
    sweep,
    subscribe(listener) {
      listeners.add(listener)
      return () => {
        listeners.delete(listener)
      }
    },
    size() {
      sweep()
      return records.size
    },
  }
}
